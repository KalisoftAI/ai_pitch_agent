class MotionRenderError(RuntimeError):
    pass


class MotionRenderCancelled(RuntimeError):
    pass


class MotionRenderer:
    """Render storyboard scenes as animated canvas graphics.

    The capture loop is the MIT-licensed Lemo-Opuscar pipeline: a static page is
    served to headless Chrome, every frame calls ``window.render(t)``, and JPEG
    screenshots are piped into FFmpeg. The page itself is generated by AI Film
    Studio and uses only local assets.
    """

    def __init__(self, settings: Settings | None = None) -> None:
        self.settings = settings or get_settings()

    def available(self) -> tuple[bool, str]:
        root = self.settings.renderer_path
        video = root / "core" / "render" / "video.mjs"
        if not video.exists():
            return False, f"Motion renderer is missing at {video}."
        node = shutil.which("node")
        if not node:
            return False, "Node.js 20+ is required for motion rendering."
        playwright = root / "node_modules" / "playwright-core" / "package.json"
        if not playwright.exists():
            return False, "Run scripts/setup_renderer.ps1 to install the renderer dependencies."
        if not self.settings.find_chrome():
            return False, "Chrome or Edge was not found. Set MOTION_CHROME_PATH to the browser executable."
        if not self._find_ffmpeg():
            return False, "FFmpeg is required for motion rendering."
        return True, f"Motion renderer ready ({node})."

    def render(
        self,
        db: Session,
        project: Project,
        scenes: list[Scene],
        *,
        job_id: str,
        output: Path,
        width: int,
        height: int,
        fps: int,
        workers: int,
        include_captions: bool,
        options: dict | None = None,
        progress: Callable[[int, str, str | None], None],
        should_cancel: Callable[[], bool],
    ) -> Path:
        ok, reason = self.available()
        if not ok:
            raise MotionRenderError(reason)
        options = options or {}

        temp_root = self.settings.storage_path / "temp" / job_id / "motion"
        page_dir = temp_root / "page"
        if page_dir.exists():
            shutil.rmtree(page_dir, ignore_errors=True)
        page_dir.mkdir(parents=True, exist_ok=True)
        template_name = str(options.get("template") or self.settings.motion_template)
        template_name = self._copy_template(page_dir, template_name)

        progress(6, "directing motion", "Building the visual direction for this film.")
        direction, direction_note = self._direction(db, project, scenes, options)
        if direction_note:
            progress(9, "directing motion", direction_note)

        progress(11, "preparing assets", "Validating and normalising visual assets.")
        assets = self._prepare_assets(db, scenes, page_dir)
        data = self._build_data(
            project,
            scenes,
            direction,
            assets,
            width=width,
            height=height,
            fps=fps,
            include_captions=include_captions,
            options=options,
            template=template_name,
        )
        (page_dir / "data.json").write_text(
            json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
        )

        output.parent.mkdir(parents=True, exist_ok=True)
        output.unlink(missing_ok=True)
        silent_video = temp_root / "silent.mp4"
        progress(
            16,
            "launching renderer",
            f"Rendering {len(scenes)} animated scenes at {width}x{height}, {fps} fps, {workers} worker(s).",
        )
        self._run_node(
            page_dir=page_dir,
            output=silent_video,
            width=width,
            height=height,
            fps=fps,
            workers=workers,
            progress=progress,
            should_cancel=should_cancel,
        )
        if not silent_video.exists() or silent_video.stat().st_size == 0:
            raise MotionRenderError("The motion renderer finished without producing a video.")

        audio_enabled = bool(options.get("audio", self.settings.motion_audio))
        if audio_enabled:
            progress(93, "mixing sound", "Adding procedural sound effects and loudness normalisation.")
            try:
                audio_path = AudioMixer(self.settings.motion_audio_sr).build(
                    data, temp_root / "mix.wav"
                )
                ffmpeg = self._find_ffmpeg()
                if ffmpeg is None:
                    raise RuntimeError("FFmpeg was not found for audio muxing.")
                AudioMixer(self.settings.motion_audio_sr).mux(
                    ffmpeg, silent_video, audio_path, output
                )
            except Exception as exc:  # noqa: BLE001 - audio is optional; keep the silent render
                progress(94, "mixing sound", f"Audio mix skipped: {exc}")
                shutil.copy2(silent_video, output)
        else:
            shutil.copy2(silent_video, output)
        if not output.exists() or output.stat().st_size == 0:
            raise MotionRenderError("The motion renderer finished without producing a final video.")
        shutil.rmtree(page_dir, ignore_errors=True)
        return output

    def _template_files(self, name: str) -> dict[str, Path]:
        template_root = (self.settings.renderer_path / "template").resolve()
        renderer_root = self.settings.renderer_path.resolve()
        if not template_root.exists():
            raise MotionRenderError(f"Motion template is missing at {template_root}.")
        manifest_path = template_root / "templates.json"
        manifest: dict = {}
        if manifest_path.exists():
            try:
                manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError) as exc:
                raise MotionRenderError(f"Invalid template manifest: {exc}") from exc
            templates = manifest.get("templates", {}) if isinstance(manifest, dict) else {}
        else:
            templates = {}
        if name not in templates:
            name = str(manifest.get("default", "default")) if isinstance(manifest, dict) else "default"
        entry = templates.get(name) if isinstance(templates, dict) else None
        if not isinstance(entry, dict):
            entry = {"html": "index.html", "css": "style.css", "js": "film.js"}

        files: dict[str, Path] = {}
        for target, key in (("index.html", "html"), ("style.css", "css"), ("film.js", "js")):
            relative = str(entry.get(key, target)).strip().lstrip("/")
            source = (template_root / relative).resolve()
            if renderer_root not in source.parents or not source.is_file():
                raise MotionRenderError(f"Motion template file is missing or unsafe: {source}.")
            files[target] = source
        return files

    def _copy_template(self, page_dir: Path, name: str | None = None) -> str:
        template_name = str(name or self.settings.motion_template).strip().lower() or "default"
        for target, source in self._template_files(template_name).items():
            shutil.copy2(source, page_dir / target)
        return template_name

    def _find_ffmpeg(self) -> str | None:
        if Path(self.settings.ffmpeg_bin).exists():
            return str(Path(self.settings.ffmpeg_bin))
        return shutil.which(self.settings.ffmpeg_bin)

    def _style(self, project: Project, options: dict | None = None) -> str:
        options = options or {}
        style = str(options.get("motion_style") or project.visual_style or "").strip().lower()
        if style in ALLOWED_STYLES:
            return style
        if project.category == "financial-education":
            return "data"
        if project.category == "erp-walkthrough":
            return "walkthrough"
        return "editorial"

    def _palette(self, project: Project, style: str) -> dict[str, str]:
        seed = sum(ord(char) for char in f"{project.id}{project.category}{style}{project.title}")
        if project.category == "financial-education":
            palette = PALETTES[seed % 2]
        elif project.category == "erp-walkthrough":
            palette = PALETTES[1 + seed % 2]
        elif style == "neon":
            palette = PALETTES[2 + seed % 2]
        elif style == "minimal":
            palette = PALETTES[5 - seed % 2]
        else:
            palette = PALETTES[seed % len(PALETTES)]
        return dict(palette)

    def _patterns(self, style: str, count: int) -> list[str]:
        base = list(STYLE_PATTERNS.get(style, STYLE_PATTERNS["swiss"]))
        if count <= 1:
            return [base[0] if base else "full"]
        patterns = [base[index % len(base)] for index in range(count)]
        if count > 2 and patterns[-1] != "quote":
            patterns[-1] = "quote"
        return patterns

    def _effects(
        self, style: str, pattern: str, options: dict | None, index: int
    ) -> list[str]:
        options = options or {}
        requested = options.get("effects")
        if not isinstance(requested, list) or not requested:
            requested = self.settings.default_motion_effects
        effects = [str(item).lower() for item in requested if str(item).lower() in ALLOWED_EFFECTS]
        if not effects:
            effects = ["grain", "vignette"]
        if pattern == "documentary":
            effects = list(dict.fromkeys(effects + ["grain", "vignette", "letterbox"]))
        elif pattern == "isometric":
            effects = list(dict.fromkeys(effects + ["bokeh"]))
        elif style == "neon":
            effects = list(dict.fromkeys(effects + ["lightleak", "chromatic"]))
        elif pattern in {"data", "infographic"}:
            effects = list(dict.fromkeys(effects + ["grid"]))
        if index % 3 == 1:
            effects = [item for item in effects if item not in {"glitch", "chromatic"}]
        return effects

    def _camera(self, pattern: str, index: int) -> str:
        if pattern == "isometric":
            return "orbit"
        if pattern in {"documentary", "story"}:
            return "push-in" if index % 2 == 0 else "pan-left"
        if pattern in {"typographic", "walkthrough"}:
            return "static"
        return ["push-in", "pan-right", "pull-out", "tilt"][index % 4]

    def _direction(
        self,
        db: Session,
        project: Project,
        scenes: list[Scene],
        options: dict | None = None,
    ) -> tuple[dict, str | None]:
        options = options or {}
        style = self._style(project, options)
        palette = self._palette(project, style)
        patterns = self._patterns(style, len(scenes))
        overrides = options.get("scene_patterns")
        if not isinstance(overrides, dict):
            overrides = {}
        accents = [palette["signal"], palette["accent"], palette["signal"], palette["accent"]]
        plan_scenes = []
        for index, _scene in enumerate(scenes):
            override = overrides.get(str(index)) or overrides.get(str(index + 1))
            pattern = str(override or patterns[index]).lower()
            if pattern not in ALLOWED_LAYOUTS:
                pattern = patterns[index]
            plan_scenes.append(
                {
                    "index": index + 1,
                    "pattern": pattern,
                    "layout": pattern,
                    "camera": self._camera(pattern, index),
                    "effects": self._effects(style, pattern, options, index),
                    "sound": "data" if pattern in {"data", "infographic"} else pattern,
                    "kicker": f"SCENE {index + 1:02d}",
                    "accent": accents[index % len(accents)],
                }
            )
        plan = {"style": style, "palette": palette, "scenes": plan_scenes}
        if not self.settings.motion_ai_direction or self.settings.mock_ai:
            return plan, None

        ai_plan, error = self._ask_ai(db, project, scenes, style)
        if ai_plan is None:
            return plan, f"AI direction unavailable ({error}); using the local motion plan."
        merged = self._merge_direction(plan, ai_plan)
        return merged, "AI motion direction applied."

    def _ask_ai(
        self, db: Session, project: Project, scenes: list[Scene], style: str
    ) -> tuple[dict | None, str]:
        scene_lines = "\n".join(
            f"{index + 1}. {scene.title} | {scene.narration[:240]} | {scene.visual_prompt[:180]}"
            for index, scene in enumerate(scenes)
        )
        prompt = (
            "Design a motion-graphics direction for a short business video.\n"
            f"Title: {project.title}\n"
            f"Category: {category_label(project.category)}\n"
            f"Topic: {project.topic}\n"
            f"Current visual style: {style}\n"
            f"Scenes:\n{scene_lines}\n\n"
            "Return ONLY valid JSON with this shape:\n"
            '{"style":"cinematic|editorial|neon|minimal|swiss|data|isometric|typographic|infographic|walkthrough|documentary|story",'
            '"palette":{"bg":"#rrggbb","panel":"#rrggbb","ink":"#rrggbb","signal":"#rrggbb","accent":"#rrggbb"},'
            '"scenes":[{"index":1,'
            '"pattern":"split|full|minimal|data|collage|quote|isometric|typographic|infographic|walkthrough|documentary|story",'
            '"camera":"static|push-in|pull-out|pan-left|pan-right|orbit|tilt",'
            '"effects":["grain","vignette","scanlines","particles","lightleak","bokeh","glitch","letterbox","grid","chromatic"],'
            '"kicker":"short label","accent":"#rrggbb"}]}\n'
            "Use one scene object per input scene. Vary patterns but keep a coherent system. "
            "Keep kickers under 28 characters. Use high contrast, one signal colour, and no external image URLs."
        )

        async def ask():
            service = get_ai_service()
            return await service.generate(
                db,
                AIGenerateRequest(
                    prompt=prompt,
                    task="motion",
                    system="You are a motion-graphics director. Return only valid JSON.",
                    project_id=project.id,
                    max_tokens=900,
                ),
            )

        try:
            result = asyncio.run(
                asyncio.wait_for(ask(), timeout=self.settings.motion_ai_timeout_seconds)
            )
        except Exception as exc:  # noqa: BLE001 - any provider failure falls back locally
            return None, str(exc)[:240]
        parsed = self._parse_json(result.text)
        if parsed is None:
            return None, "the model did not return valid JSON"
        return parsed, ""

    def _parse_json(self, text: str) -> dict | None:
        start = text.find("{")
        end = text.rfind("}")
        if start < 0 or end <= start:
            return None
        try:
            value = json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            return None
        return value if isinstance(value, dict) else None

    def _merge_direction(self, base: dict, incoming: dict) -> dict:
        result = json.loads(json.dumps(base))
        style = str(incoming.get("style", "")).lower()
        if style in ALLOWED_STYLES:
            result["style"] = style
        palette = incoming.get("palette")
        if isinstance(palette, dict):
            for key in ("bg", "panel", "ink", "signal", "accent"):
                value = palette.get(key)
                if isinstance(value, str) and HEX_COLOR.match(value):
                    result["palette"][key] = value
        plans = incoming.get("scenes")
        if isinstance(plans, list):
            by_index = {
                int(item.get("index")): item
                for item in plans
                if isinstance(item, dict) and str(item.get("index", "")).isdigit()
            }
            for item in result["scenes"]:
                incoming_scene = by_index.get(item["index"])
                if not incoming_scene:
                    continue
                layout = str(
                    incoming_scene.get("pattern") or incoming_scene.get("layout") or ""
                ).lower()
                if layout in ALLOWED_LAYOUTS:
                    item["pattern"] = layout
                    item["layout"] = layout
                camera = str(incoming_scene.get("camera", "")).lower()
                if camera in ALLOWED_CAMERAS:
                    item["camera"] = camera
                effects = incoming_scene.get("effects")
                if isinstance(effects, list):
                    selected = [
                        str(value).lower()
                        for value in effects
                        if str(value).lower() in ALLOWED_EFFECTS
                    ]
                    if selected:
                        item["effects"] = selected
                kicker = incoming_scene.get("kicker")
                if isinstance(kicker, str) and kicker.strip():
                    item["kicker"] = kicker.strip()[:32]
                accent = incoming_scene.get("accent")
                if isinstance(accent, str) and HEX_COLOR.match(accent):
                    item["accent"] = accent
        return result

    def _prepare_assets(
        self, db: Session, scenes: list[Scene], page_dir: Path
    ) -> dict[str, str | None]:
        assets_dir = page_dir / "assets"
        assets_dir.mkdir(parents=True, exist_ok=True)
        library = list(
            db.execute(
                select(Asset)
                .where(Asset.media_type == "image")
                .order_by(Asset.favorite.desc(), Asset.created_at.desc())
            )
            .scalars()
            .all()
        )
        result: dict[str, str | None] = {}
        used: set[str] = set()
        for scene in scenes:
            asset = db.get(Asset, scene.asset_id) if scene.asset_id else None
            if asset is not None and not self._usable_image(asset):
                asset = None
            if asset is None:
                asset = self._pick_library_asset(scene, library, used)
            if asset is None or not self._usable_image(asset):
                result[scene.id] = None
                continue
            source = Path(asset.path)
            target = assets_dir / f"scene-{scene.order_index:02d}.jpg"
            if not self._preprocess_asset(source, target):
                result[scene.id] = None
                continue
            result[scene.id] = f"assets/{target.name}"
            used.add(asset.id)
        return result

    def _preprocess_asset(self, source: Path, target: Path) -> bool:
        try:
            with Image.open(source) as image:
                image = ImageOps.exif_transpose(image)
                if getattr(image, "is_animated", False):
                    image.seek(0)
                image = image.convert("RGB")
                image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
                target.parent.mkdir(parents=True, exist_ok=True)
                image.save(target, format="JPEG", quality=92, optimize=True, progressive=True)
            return target.exists() and target.stat().st_size > 0
        except Exception:  # noqa: BLE001 - corrupt or unsupported assets fall back to graphics
            target.unlink(missing_ok=True)
            return False

    def _usable_image(self, asset: Asset) -> bool:
        path = Path(asset.path)
        return asset.media_type == "image" and path.exists() and path.suffix.lower() in IMAGE_SUFFIXES

    def _pick_library_asset(
        self, scene: Scene, library: list[Asset], used: set[str]
    ) -> Asset | None:
        if not library:
            return None
        candidates = [asset for asset in library if asset.id not in used] or library
        words = set(
            re.findall(
                r"[a-z0-9]+",
                f"{scene.title} {scene.narration} {scene.visual_prompt}".lower(),
            )
        )

        def score(asset: Asset) -> tuple[int, int]:
            tags = {str(tag).lower() for tag in (asset.tags or [])}
            overlap = len(words & tags)
            return (overlap, 1 if asset.favorite else 0)

        return max(candidates, key=score)

    def _build_data(
        self,
        project: Project,
        scenes: list[Scene],
        direction: dict,
        assets: dict[str, str | None],
        *,
        width: int,
        height: int,
        fps: int,
        include_captions: bool,
        options: dict | None = None,
        template: str = "default",
    ) -> dict:
        options = options or {}
        plans = {
            int(item["index"]): item
            for item in direction.get("scenes", [])
            if isinstance(item, dict) and str(item.get("index", "")).isdigit()
        }
        palette = direction.get("palette") or self._palette(project, "swiss")
        data_scenes: list[dict] = []
        cursor = 0.0
        for index, scene in enumerate(scenes):
            duration = max(1.0, float(scene.duration_seconds or 5.0))
            plan = plans.get(index + 1, {})
            transition = (scene.transition or "wipe").lower()
            pattern = str(plan.get("pattern") or plan.get("layout") or "split").lower()
            if pattern not in ALLOWED_LAYOUTS:
                pattern = "split"
            camera = str(plan.get("camera") or "static").lower()
            if camera not in ALLOWED_CAMERAS:
                camera = "static"
            effects = plan.get("effects")
            if not isinstance(effects, list):
                effects = self._effects(str(direction.get("style", "swiss")), pattern, options, index)
            data_scenes.append(
                {
                    "index": index + 1,
                    "title": scene.title or f"Scene {index + 1}",
                    "narration": scene.narration or "",
                    "visual": scene.visual_prompt or "",
                    "asset": assets.get(scene.id),
                    "start": round(cursor, 3),
                    "duration": round(duration, 3),
                    "layout": pattern,
                    "pattern": pattern,
                    "camera": camera,
                    "effects": [str(item) for item in effects if str(item) in ALLOWED_EFFECTS],
                    "sound": plan.get("sound", pattern),
                    "kicker": plan.get("kicker", f"SCENE {index + 1:02d}"),
                    "accent": plan.get("accent", palette.get("signal", "#ff4d2e")),
                    "transition": transition if transition in ALLOWED_TRANSITIONS else "wipe",
                    "stat": self._stat(scene),
                    "chart": self._chart(scene),
                }
            )
            cursor += duration
        return {
            "title": project.title,
            "topic": project.topic,
            "category": category_label(project.category),
            "style": direction.get("style", "swiss"),
            "palette": palette,
            "width": width,
            "height": height,
            "fps": fps,
            "duration": round(max(1.0, cursor), 3),
            "showCaptions": bool(include_captions),
            "audio": bool(options.get("audio", self.settings.motion_audio)),
            "template": template,
            "scenes": data_scenes,
        }

    def _chart(self, scene: Scene) -> list[float]:
        seed = sum(ord(char) for char in f"{scene.id}{scene.title}{scene.order_index}")
        rnd = random.Random(seed)
        return [round(0.18 + rnd.random() * 0.82, 3) for _ in range(9)]

    def _stat(self, scene: Scene) -> dict | None:
        match = NUMBER.search(f"{scene.title} {scene.narration}")
        if not match:
            return None
        raw = match.group(0).strip()
        try:
            value = float(match.group(1).replace(",", ""))
        except ValueError:
            return None
        suffix = (match.group(2) or "").lower()
        if suffix in {"k", "m", "bn", "billion", "million"}:
            value *= {"k": 1_000, "m": 1_000_000, "bn": 1_000_000_000, "billion": 1_000_000_000, "million": 1_000_000}[suffix]
        return {"value": value, "raw": raw}

    def _run_node(
        self,
        *,
        page_dir: Path,
        output: Path,
        width: int,
        height: int,
        fps: int,
        workers: int,
        progress: Callable[[int, str, str | None], None],
        should_cancel: Callable[[], bool],
    ) -> None:
        root = self.settings.renderer_path
        node = shutil.which("node") or "node"
        video = root / "core" / "render" / "video.mjs"
        chrome = self.settings.find_chrome()
        command = [
            node,
            str(video),
            str(page_dir),
            "--fps",
            str(max(1, fps)),
            "--workers",
            str(max(1, workers)),
            "--size",
            f"{width}x{height}",
            "--out",
            str(output),
        ]
        env = os.environ.copy()
        if chrome:
            env["PLAYWRIGHT_CHROME"] = chrome
        env["RENDER_SLOTS"] = "1"
        env["RENDER_MIN_FREE"] = "20"
        process = subprocess.Popen(
            command,
            cwd=str(root),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
            env=env,
        )
        stop = threading.Event()
        deadline = time.monotonic() + max(30, self.settings.motion_timeout_seconds)
        cancelled = False

        def watch() -> None:
            nonlocal cancelled
            while not stop.wait(1.0):
                if should_cancel():
                    cancelled = True
                    self._terminate(process)
                    return
                if time.monotonic() > deadline:
                    cancelled = True
                    self._terminate(process)
                    return

        watcher = threading.Thread(target=watch, daemon=True)
        watcher.start()
        lines: list[str] = []
        last_log = 0.0
        code = -1
        try:
            assert process.stdout is not None
            for raw in process.stdout:
                line = raw.rstrip()
                if not line:
                    continue
                lines.append(line)
                lines = lines[-60:]
                match = FRAME_LINE.match(line)
                if match:
                    done = int(match.group(2))
                    total = max(1, int(match.group(3)))
                    pct = 18 + int((done / total) * 70)
                    message = line if time.monotonic() - last_log > 4 else None
                    if message:
                        last_log = time.monotonic()
                    progress(pct, f"rendering frames {done}/{total}", message)
                elif line.startswith("done ") or "done " in line:
                    progress(92, "finalizing video", line)
                elif "error" in line.lower() or "failed" in line.lower():
                    progress(18, "rendering frames", line)
            code = process.wait()
        finally:
            stop.set()
            watcher.join(timeout=2)
            if process.poll() is None:
                self._terminate(process)

        if cancelled:
            if should_cancel():
                raise MotionRenderCancelled("Render cancelled.")
            raise MotionRenderError(
                f"Motion render timed out after {self.settings.motion_timeout_seconds} seconds."
            )
        if code != 0:
            tail = "\n".join(lines[-12:])
            raise MotionRenderError(
                f"Motion renderer exited with code {code}. {tail[-1200:]}".strip()
            )

    def _terminate(self, process: subprocess.Popen) -> None:
        if process.poll() is not None:
            return
        if os.name == "nt":
            subprocess.run(
                ["taskkill", "/F", "/T", "/PID", str(process.pid)],
                capture_output=True,
                check=False,
            )
        else:
            process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
